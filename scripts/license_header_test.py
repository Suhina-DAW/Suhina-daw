"""Check `scripts/license_header.py`, the licence header CI keeps in every source file.

    python scripts/license_header_test.py
"""

from __future__ import annotations

import sys

from license_header import PORTED, ROOT, apply, skip_reason

RS = "// Copyright (C) 2026 The Suhina contributors\n// SPDX-License-Identifier: GPL-3.0-or-later\n\n"
PY = "# Copyright (C) 2026 The Suhina contributors\n# SPDX-License-Identifier: GPL-3.0-or-later\n\n"
FM_NOTICE = "// Ported from MSFA.\n// Copyright 2012 Google Inc.\n// Licensed under the Apache License, Version 2.0.\n\n//! Doc.\n"

# (what it checks, path, file before, file after or None when it must stay as it was)
CASES = [
    ("a Rust file gets the header", "crates/x/src/a.rs", "fn main() {}\n", RS + "fn main() {}\n"),
    ("a //! module doc stays first after it", "crates/x/src/b.rs", "//! Doc.\n\nuse x;\n", RS + "//! Doc.\n\nuse x;\n"),
    ("#![...] is not a #! line", "crates/x/src/c.rs", "#![allow(x)]\n", RS + "#![allow(x)]\n"),
    (
        "a Python #! line stays first, the docstring and __future__ after the header",
        "scripts/a.py",
        '#!/usr/bin/env python3\n"""Doc."""\n\nfrom __future__ import annotations\n',
        '#!/usr/bin/env python3\n' + PY + '"""Doc."""\n\nfrom __future__ import annotations\n',
    ),
    (
        "an encoding line stays after the #! line",
        "scripts/b.py",
        "#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\nx = 1\n",
        "#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n" + PY + "x = 1\n",
    ),
    ("a Python file without #! starts with it", "scripts/c.py", '"""Doc."""\n', PY + '"""Doc."""\n'),
    ("a shell script keeps its #! line", "scripts/a.sh", "#!/usr/bin/env sh\necho\n", "#!/usr/bin/env sh\n" + PY + "echo\n"),
    ("a PowerShell script gets # lines", "scripts/a.ps1", "Write-Host x\n", PY + "Write-Host x\n"),
    ("CRLF line ends are kept", "scripts/d.py", "x = 1\r\n", PY.replace("\n", "\r\n") + "x = 1\r\n"),
    ("an empty file gets the header alone", "crates/x/src/e.rs", "", RS[:-1]),
    (
        "ported code keeps its notice and gets only its own SPDX line",
        "devices/fm-synth/src/core.rs",
        FM_NOTICE,
        "// SPDX-License-Identifier: Apache-2.0\n\n" + FM_NOTICE,
    ),
    (
        "the Signalsmith port gets MIT",
        "crates/stretch/src/stft.rs",
        "//! Ported from Signalsmith Linear (MIT).\n",
        "// SPDX-License-Identifier: MIT\n\n//! Ported from Signalsmith Linear (MIT).\n",
    ),
    ("a Suhina file of a ported crate gets the header", "devices/fm-synth/src/params.rs", "//! Doc.\n", RS + "//! Doc.\n"),
    ("another copyright notice outside PORTED is left alone", "crates/x/src/f.rs", FM_NOTICE, None),
    ("part of the header is left alone", "crates/x/src/g.rs", "// Copyright (C) 2026 The Suhina contributors\n", None),
    ("a generated file is left alone", "crates/x/src/h.rs", "// @generated by a tool\nfn f() {}\n", None),
    ("other files are left alone", "docs/a.md", "# Title\n", None),
]

# (path, why it is skipped)
SKIPPED = [
    ("third_party/asiosdk/common/asio.py", "vendored (third_party/)"),
    ("crates/flp/tests/fixtures/a.rs", "test fixture"),
    ("crates/engine/tests/golden/a.py", "test fixture"),
    ("crates/media/tests/data/make.py", "test fixture"),
    ("crates/x/testdata/a.rs", "test fixture"),
]

NOT_SKIPPED = ["crates/flp/tests/fixtures.rs", "scripts/stems-fixture.py"]


def run() -> int:
    failed = 0
    total = 0

    def report(ok: bool, what: str) -> None:
        nonlocal failed, total
        total += 1
        failed += not ok
        print(f"{'PASS' if ok else 'FAIL'}  {what}")

    for what, path, before, after in CASES:
        got, _ = apply(path, before)
        expected = before if after is None else after
        report(got == expected, what + ("" if got == expected else f": got {got!r}"))
        again, done = apply(path, got)
        report(again == got, f"running it again changes nothing ({path}, {done})")
    for path, why in SKIPPED:
        found = skip_reason(path)
        report(found == why, f"{path} is skipped: {why}" + ("" if found == why else f" (got {found})"))
    for path in NOT_SKIPPED:
        report(skip_reason(path) is None, f"{path} is a source file, not a fixture")
    for path in PORTED:
        report((ROOT / path).is_file(), f"ported file {path} exists")
    print(f"{total - failed}/{total} checks passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(run())
